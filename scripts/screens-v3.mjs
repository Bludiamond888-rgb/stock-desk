import { webkit, devices } from 'playwright'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { serve } from './serve.mjs'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { server, url } = await serve(path.join(root, 'dist'))
const out = (f) => path.join(root, 'screens', f)
const b = await webkit.launch()
const ctx = await b.newContext({ ...devices['iPhone 13'], timezoneId: 'America/New_York' })
const page = await ctx.newPage()
const ext = []; page.on('request', (r) => { if (!r.url().startsWith(url)) ext.push(r.url()) })
page.on('pageerror', (e) => { console.log('PAGE ERROR', e.message); process.exitCode = 1 })
await page.goto(url + '#/home'); await page.click('button:has-text("Load demo data")'); await page.waitForSelector('[data-testid=stock-value]')
await page.goto(url + '#/products'); await page.waitForSelector('[data-testid=product-card]')
await page.click('button:has-text("＋ Add")'); await page.fill('input[placeholder="Product name"]', 'LED Strip Light')
await page.click('button:has-text("Generate")'); await page.waitForSelector('[data-testid=form-label] img')
console.log('generated', await page.inputValue('.sku-row input'))
await page.waitForTimeout(300); await page.screenshot({ path: out('v3-1-product-form-sku-qr-iphone-webkit.png') })
await page.click('[aria-label=Close]')
await page.click('button:has-text("Print all labels")'); await page.waitForSelector('[data-testid=label-sheet] img')
await page.waitForTimeout(300); await page.screenshot({ path: out('v3-2-label-sheet-iphone-webkit.png') })
await page.click('[aria-label=Close]')
await page.goto(url + '#/scan'); await page.waitForSelector('.scan-btn')
await page.evaluate(() => window.__scanCode('NEW-XYZ-42')); await page.waitForSelector('[data-testid=unknown-code]')
await page.waitForTimeout(300); await page.screenshot({ path: out('v3-3-unknown-scan-iphone-webkit.png') })
await page.click('button:has-text("Add as new product")'); await page.waitForSelector('.sku-row input')
console.log('prefilled', await page.inputValue('.sku-row input'))
await page.fill('input[placeholder="Product name"]', 'Mystery item'); await page.click('button:has-text("Save product")')
await page.waitForSelector('.picked'); console.log('back on scan with', await page.textContent('.picked b'), page.url())
console.log('external requests:', ext.length)
await b.close(); server.close()
